import type { SkillId } from '@/lib/types'

/**
 * The learning units of the 14-week course (REPS_2_MASTER_SPEC.md §17), in
 * teaching order. A unit references existing sections and reps by id; it never
 * copies content. New course content lives in data/exercises/course and is
 * referenced the same way.
 *
 * - `sections`: the unit's path, in order (lesson-level reps first, then drills).
 * - `optional`: sections offered when ahead, never required.
 * - `prerequisites`: units whose gate must be cleared first (hard locks).
 * - `targets`: LeetCode numbers this unit is the ladder for (capstones).
 */

export type CurriculumPhase = 'foundation' | 'problem-solving' | 'core-dsa' | 'patterns' | 'transfer' | 'interview'

export interface LearningUnit {
  id: string
  week: number
  title: string
  phase: CurriculumPhase
  /** One line: why this unit exists. */
  purpose: string
  prerequisites: string[]
  /** Lessons first (data/course/lessons.ts) or concept guides (data/concepts.ts). */
  lessonIds: string[]
  workedExampleIds: string[]
  /** Inventory: the sections this unit's material lives in (practice and repair; never all required). */
  sections: string[]
  /**
   * REQUIRED PATH (REPS_2_1_SPEC.md §8): curated rep ids, in teaching order. Small enough that the
   * week's required work (paths + gate passes + required targets) fits the weekly target with room
   * for retrieval. Every other rep of the unit is repair inventory or optional practice.
   */
  path?: string[]
  /** Offered when ahead, never required. */
  optional?: string[]
  /** Beyond the Feb 1 scope: available, never required, never counted against the week. */
  stretch?: string[]
  /** Warm-up and cold sections that are not gates: they come back through spaced retrieval. */
  retrieval?: string[]
  /** Mixed-section reps deferred until their actual teaching week. */
  deferred?: string[]
  gateIds: string[]
  labIds: string[]
  /** REQUIRED target problems (outside), due once the unit is ready. */
  targets: number[]
  /** Targets offered once the unit is ready and their bridge is clean; never required. */
  readinessTargets?: number[]
  retrievalSkills: SkillId[]
}

